// -----------------------------------------------------------------------------
// Builds src/icons.js: the notification icons, white PNG renderings of
// Material Design Icons (Pictogrammers, Apache-2.0), base64-encoded.
//
// Run by hand when the icon list changes, never by the CI or the image:
//   npm pack @mdi/svg@7.4.47 && tar xzf mdi-svg-7.4.47.tgz
//   node scripts/build-icons.mjs package/svg   (needs Playwright and a Chromium)
//
// "Notifications for Android TV" takes the icon as an image file; TvOverlay
// takes the `mdi:<name>` reference itself; PiPup has no icon.
// -----------------------------------------------------------------------------

import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { chromium } from 'playwright';

// key (manifest option value, frozen once published) -> MDI icon name
export const ICON_SOURCES = {
  doorbell: 'doorbell',
  bell: 'bell-ring',
  camera: 'cctv',
  alert: 'alert',
  info: 'information',
  door: 'door-open',
  package: 'package-variant-closed',
  mail: 'email',
  phone: 'phone',
  washing_machine: 'washing-machine',
  dishwasher: 'dishwasher',
  food: 'silverware-fork-knife',
  thermometer: 'thermometer',
  water_leak: 'water-alert',
  fire: 'fire',
  weather: 'weather-lightning-rainy',
  car: 'car',
  home: 'home',
  baby: 'baby-carriage',
};

const SIZE = 96;
const svgDir = process.argv[2];
if (!svgDir) {
  console.error('Usage: node scripts/build-icons.mjs <path to @mdi/svg/svg>');
  process.exit(1);
}

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH });
const page = await browser.newPage({ viewport: { width: SIZE, height: SIZE } });
const icons = {};
for (const [key, name] of Object.entries(ICON_SOURCES)) {
  const svg = await readFile(join(svgDir, `${name}.svg`), 'utf8');
  const path = svg.match(/ d="([^"]+)"/)[1];
  await page.setContent(
    `<html><body style="margin:0;background:transparent">` +
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="${SIZE}" height="${SIZE}">` +
      `<path fill="#ffffff" d="${path}"/></svg></body></html>`,
  );
  const png = await page.screenshot({ omitBackground: true, type: 'png' });
  icons[key] = { mdi: name, png: png.toString('base64') };
}
await browser.close();

const lines = Object.entries(icons).map(
  ([key, { mdi, png }]) => `  ${key}: {\n    mdi: '${mdi}',\n    png: '${png}',\n  },`,
);
await writeFile(
  new URL('../src/icons.js', import.meta.url),
  `// -----------------------------------------------------------------------------
// Notification icons. GENERATED by scripts/build-icons.mjs: do not edit by hand.
//
// White ${SIZE} x ${SIZE} PNG renderings of Material Design Icons by Pictogrammers
// (https://pictogrammers.com, icons under the Apache-2.0 license). The keys are
// the option values of the scene action's "icon" field: frozen once published.
// -----------------------------------------------------------------------------

export const ICONS = {
${lines.join('\n')}
};
`,
);
console.log(`src/icons.js: ${Object.keys(icons).length} icons`);
